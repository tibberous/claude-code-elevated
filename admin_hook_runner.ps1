<#
  admin_hook_runner.ps1 - the SYSTEM elevation primitive (pure PowerShell, ZERO dependencies).

  Runs as NT AUTHORITY\SYSTEM (installed by bootstrap.ps1, as a scheduled task or a service).
  Each tick: if _sysfix.ps1 exists next to this script, execute it as SYSTEM and delete it.
  Write logs\heartbeat.txt. The queued script is generated by the CLIENT (run_elevated.py or
  any language - it is just file I/O). Deliberately minimal: everything here runs as SYSTEM.

  Two shapes, same file:
    (default)              drain once + heartbeat + exit     <- scheduled task fires it @60s
    -Loop [-Interval N]    drain forever every N seconds      <- Windows service (instant-ish)

  No Python required - PowerShell ships with every Windows install.
#>
param(
  [switch]$Loop,
  [double]$Interval = 3
)

$Base      = Split-Path -Parent $MyInvocation.MyCommand.Path
$Queue     = Join-Path $Base '_sysfix.ps1'
$Heartbeat = Join-Path $Base 'logs\heartbeat.txt'

function Invoke-Drain {
  $ran = $false
  if (Test-Path $Queue) {
    try {
      & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $Queue | Out-Null
    } finally {
      Remove-Item $Queue -Force -ErrorAction SilentlyContinue
    }
    $ran = $true
  }
  try {
    New-Item -ItemType Directory -Force -Path (Split-Path $Heartbeat) | Out-Null
    $stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
    "$stamp  ran_as=$env:USERNAME  drained_queue=$ran" | Set-Content -Encoding utf8 -Path $Heartbeat
  } catch {}
}

if ($Loop) {
  while ($true) {
    Invoke-Drain
    Start-Sleep -Seconds ([Math]::Max(0.5, $Interval))
  }
} else {
  Invoke-Drain
}
